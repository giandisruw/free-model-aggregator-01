/** The text of a Gemini candidate's content parts. */
function geminiText(body: Json): string {
  const candidates = Array.isArray(body.candidates) ? body.candidates : [];
  const candidate = isRecord(candidates[0]) ? candidates[0] : {};
  const content = isRecord(candidate.content) ? candidate.content : {};
  const parts = Array.isArray(content.parts) ? content.parts : [];
  return parts.flatMap((p) => (isRecord(p) && typeof p.text === 'string' ? [p.text] : [])).join('');
}

/** Gemini usageMetadata as {input, output} token counts. */
function geminiUsage(body: Json): { input: number; output: number } {
  const meta = isRecord(body.usageMetadata) ? body.usageMetadata : {};
  return { input: numberOrZero(meta.promptTokenCount), output: numberOrZero(meta.candidatesTokenCount) };
}

/** A Gemini generateContent answer as an OpenAI Chat Completions object. */
export function geminiToOpenAI(body: Json, model: string): Json {
  const candidates = Array.isArray(body.candidates) ? body.candidates : [];
  const candidate = isRecord(candidates[0]) ? candidates[0] : {};
  const usage = geminiUsage(body);
  return {
    id: 'chatcmpl-agg',
    object: 'chat.completion',
    created: FIXED_OPENAI_CREATED,
    model,
    choices: [{ index: 0, message: { role: 'assistant', content: geminiText(body) }, finish_reason: finishReasonOf(candidate.finishReason), logprobs: null }],
    usage: { prompt_tokens: usage.input, completion_tokens: usage.output, total_tokens: usage.input + usage.output },
  };
}

/** A Gemini generateContent answer as an Anthropic Messages object. */
export function geminiToAnthropic(body: Json, model: string): Json {
  const candidates = Array.isArray(body.candidates) ? body.candidates : [];
  const candidate = isRecord(candidates[0]) ? candidates[0] : {};
  const usage = geminiUsage(body);
  return {
    id: 'msg_agg',
    type: 'message',
    role: 'assistant',
    model,
    content: [{ type: 'text', text: geminiText(body) }],
    stop_reason: stopReasonOf(finishReasonOf(candidate.finishReason)),
    stop_sequence: null,
    usage: { input_tokens: usage.input, output_tokens: usage.output },
  };
}

/** An Anthropic Messages answer as an OpenAI Chat Completions object. */
export function anthropicToOpenAIResponse(body: Json, model: string): Json {
  const content = Array.isArray(body.content) ? body.content : [];
  const text = content.flatMap((b) => (isRecord(b) && b.type === 'text' && typeof b.text === 'string' ? [b.text] : [])).join('');
  const calls = content.flatMap((b) => {
    if (!isRecord(b) || b.type !== 'tool_use') return [];
    return [{ id: typeof b.id === 'string' ? b.id : 'toolu_unknown', type: 'function', function: { name: typeof b.name === 'string' ? b.name : '', arguments: JSON.stringify(isRecord(b.input) ? b.input : {}) } }];
  });
  const usage = isRecord(body.usage) ? body.usage : {};
  const message: Json = { role: 'assistant', content: text };
  if (calls.length > 0) message.tool_calls = calls;
  return {
    id: 'chatcmpl-agg',
    object: 'chat.completion',
    created: FIXED_OPENAI_CREATED,
    model,
    choices: [{ index: 0, message, finish_reason: finishReasonOf(body.stop_reason), logprobs: null }],
    usage: { prompt_tokens: numberOrZero(usage.input_tokens), completion_tokens: numberOrZero(usage.output_tokens), total_tokens: numberOrZero(usage.input_tokens) + numberOrZero(usage.output_tokens) },
  };
}

/** Split text into the same 13-character pieces the providers stream in. */
export function splitText(text: string): string[] {
  const pieces: string[] = [];
  for (let at = 0; at < text.length; at += 13) pieces.push(text.slice(at, at + 13));
  return pieces.length === 0 ? [''] : pieces;
}

/** One OpenAI SSE chunk object for a streamed completion. */
function openAIChunk(model: string, delta: Json, finish: string | null): Json {
  return { id: 'chatcmpl-agg', object: 'chat.completion.chunk', created: FIXED_OPENAI_CREATED, model, choices: [{ index: 0, delta, finish_reason: finish }] };
}

/** Gemini stream frames as an OpenAI SSE stream: role, content pieces, finish, usage, [DONE]. */
export function openAIEventsFromGemini(frames: { event: string | null; data: string }[], model: string): string[] {
  let text = '';
  let usage = { input: 0, output: 0 };
  let finish = 'STOP';
  for (const frame of frames) {
    let value: unknown;
    try {
      value = JSON.parse(frame.data);
    } catch {
      continue;
    }
    if (!isRecord(value)) continue;
    text += geminiText(value);
    if (isRecord(value.usageMetadata)) usage = geminiUsage(value);
    const candidates = Array.isArray(value.candidates) ? value.candidates : [];
    const candidate = isRecord(candidates[0]) ? candidates[0] : {};
    if (typeof candidate.finishReason === 'string') finish = candidate.finishReason;
  }
  const out: string[] = [sseEvent(null, openAIChunk(model, { role: 'assistant', content: '' }, null))];
  for (const piece of splitText(text)) out.push(sseEvent(null, openAIChunk(model, { content: piece }, null)));
  out.push(sseEvent(null, openAIChunk(model, {}, finishReasonOf(finish))));
  out.push(sseEvent(null, { id: 'chatcmpl-agg', object: 'chat.completion.chunk', created: FIXED_OPENAI_CREATED, model, choices: [], usage: { prompt_tokens: usage.input, completion_tokens: usage.output, total_tokens: usage.input + usage.output } }));
  out.push('data: [DONE]\n\n');
  return out;
}

/** Gemini stream frames as an Anthropic SSE stream, with the real usage in both events. */
export function anthropicEventsFromGemini(frames: { event: string | null; data: string }[], model: string): string[] {
  let text = '';
  let usage = { input: 0, output: 0 };
  let finish = 'STOP';
  for (const frame of frames) {
    let value: unknown;
    try {
      value = JSON.parse(frame.data);
    } catch {
      continue;
    }
    if (!isRecord(value)) continue;
    text += geminiText(value);
    if (isRecord(value.usageMetadata)) usage = geminiUsage(value);
    const candidates = Array.isArray(value.candidates) ? value.candidates : [];
    const candidate = isRecord(candidates[0]) ? candidates[0] : {};
    if (typeof candidate.finishReason === 'string') finish = candidate.finishReason;
  }
  const out: string[] = [
    sseEvent('message_start', { type: 'message_start', message: { id: 'msg_stream', type: 'message', role: 'assistant', model, content: [], stop_reason: null, stop_sequence: null, usage: { input_tokens: usage.input, output_tokens: 0 } } }),
    sseEvent('content_block_start', { type: 'content_block_start', index: 0, content_block: { type: 'text', text: '' } }),
  ];
  for (const piece of splitText(text)) out.push(sseEvent('content_block_delta', { type: 'content_block_delta', index: 0, delta: { type: 'text_delta', text: piece } }));
  out.push(
    sseEvent('content_block_stop', { type: 'content_block_stop', index: 0 }),
    sseEvent('message_delta', { type: 'message_delta', delta: { stop_reason: stopReasonOf(finishReasonOf(finish)), stop_sequence: null }, usage: { output_tokens: usage.output } }),
    sseEvent('message_stop', { type: 'message_stop' }),
  );
  return out;
}

/**
 * An Anthropic SSE stream as OpenAI SSE events: role, content pieces, tool-call deltas,
 * finish, usage, [DONE]. `frames` are the provider stream's parsed frames.
 */
export function openAIEventsFromAnthropic(frames: { event: string | null; data: string }[], model: string): string[] {
  let text = '';
  let inputTokens = 0;
  let outputTokens = 0;
  let stop = 'end_turn';
  const toolCalls: { id: string; name: string; arguments: string }[] = [];
  for (const frame of frames) {
    let value: unknown;
    try {
      value = JSON.parse(frame.data);
    } catch {
      continue;
    }
    if (!isRecord(value)) continue;
    if (frame.event === 'message_start' && isRecord(value.message) && isRecord(value.message.usage)) {
      inputTokens = numberOrZero(value.message.usage.input_tokens);
    }
    if (frame.event === 'content_block_start' && isRecord(value.content_block) && value.content_block.type === 'tool_use') {
      toolCalls.push({ id: typeof value.content_block.id === 'string' ? value.content_block.id : `toolu_${toolCalls.length}`, name: typeof value.content_block.name === 'string' ? value.content_block.name : '', arguments: '' });
    }
    if (frame.event === 'content_block_delta' && isRecord(value.delta)) {
      if (value.delta.type === 'text_delta' && typeof value.delta.text === 'string') text += value.delta.text;
      if (value.delta.type === 'input_json_delta' && typeof value.delta.partial_json === 'string' && typeof value.index === 'number' && toolCalls[value.index] !== undefined) {
        toolCalls[value.index].arguments += value.delta.partial_json;
      }
    }
    if (frame.event === 'message_delta') {
      if (isRecord(value.delta) && typeof value.delta.stop_reason === 'string') stop = value.delta.stop_reason;
      if (isRecord(value.usage)) outputTokens = numberOrZero(value.usage.output_tokens);
    }
  }
  const out: string[] = [sseEvent(null, openAIChunk(model, { role: 'assistant', content: '' }, null))];
  for (const piece of splitText(text)) out.push(sseEvent(null, openAIChunk(model, { content: piece }, null)));
  for (let i = 0; i < toolCalls.length; i++) {
    const call = toolCalls[i];
    out.push(sseEvent(null, openAIChunk(model, { tool_calls: [{ index: i, id: call.id, type: 'function', function: { name: call.name, arguments: call.arguments } }] }, null)));
  }
  out.push(sseEvent(null, openAIChunk(model, {}, finishReasonOf(stop))));
  out.push(sseEvent(null, { id: 'chatcmpl-agg', object: 'chat.completion.chunk', created: FIXED_OPENAI_CREATED, model, choices: [], usage: { prompt_tokens: inputTokens, completion_tokens: outputTokens, total_tokens: inputTokens + outputTokens } }));
  out.push('data: [DONE]\n\n');
  return out;
}
